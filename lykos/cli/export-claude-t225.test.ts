// Sealed acceptance test for `lykos export claude` (ADR-0056).
//
// Every test drives the real CLI entry in a temporary project with a temporary
// HOME (HOME and USERPROFILE both point at it, so `os.homedir()` resolves there
// on every platform). Nothing here imports the command's own module; the only
// Lykos import is the specialist loader that already exists, used to derive
// the expected set of exposed specialists.
//
// Rulings this test pins (the full list is in the task file, t225-rulings.txt):
// - Exposed = every specialist whose effective role is `subagent` or `all` (an absent role is `all`),
//   shipped, user (~/.lykos/specialists) and project (.lykos/specialists),
//   project beating user beating shipped by name. `primary` is not
//   exposed (same set T222 lists as `lykos_<name>` tools).
// - File: `<agents>/lykos-<name>.md`, YAML frontmatter with `name: lykos-<name>`,
//   `description` containing the winning specialist file's description,
//   `model: haiku`, and `tools` limited to exactly `mcp__lykos__lykos_<name>`.
//   The file contains the marker text `generated by lykos export claude`. The body
//   tells the agent to call `mcp__lykos__lykos_<name>` with the brief and return
//   the result unchanged.
// - `.mcp.json` gains `mcpServers.lykos` whose command line runs `lykos mcp`;
//   every other server entry and top-level key is kept.
// - A `lykos-<name>.md` without the marker is refused: left byte-identical,
//   named on stderr, exit non-zero; the other files are still written.
// - Re-running regenerates its own (marked) files; a marked file for a
//   specialist no longer exposed is deleted; an unmarked file never is.
// - `--global` writes agents to `~/.claude/agents/`, does not touch
//   `~/.claude.json`, the project's `.mcp.json` or `.claude/`, and prints the
//   `claude mcp add` command for user scope instead.

import assert from "node:assert/strict";
import { spawnSync, type SpawnSyncReturns } from "node:child_process";
import { existsSync, mkdirSync, mkdtempSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { describe, it } from "node:test";
import { parse as parseYaml } from "yaml";
import { discoverSpecialists } from "../config/specialists.js";

const CLI = join(dirname(fileURLToPath(import.meta.url)), "..", "cli.ts");
// The temp project has no node_modules, so tsx is named by URL.
const TSX = import.meta.resolve("tsx");
const MARKER = "generated by lykos export claude";
const BUILTIN_SUBAGENTS = ["explore", "general", "implementer", "review", "test-writer"];

interface Sandbox {
  project: string;
  home: string;
  cleanup: () => void;
}

function sandbox(): Sandbox {
  const root = mkdtempSync(join(tmpdir(), "lykos-export-claude-"));
  const project = join(root, "project");
  const home = join(root, "home");
  mkdirSync(project, { recursive: true });
  mkdirSync(home, { recursive: true });
  return { project, home, cleanup: () => rmSync(root, { recursive: true, force: true }) };
}

function exportClaude(sb: Sandbox, extra: string[] = []): SpawnSyncReturns<string> {
  return spawnSync(process.execPath, ["--import", TSX, CLI, "export", "claude", ...extra], {
    cwd: sb.project,
    encoding: "utf8",
    input: "",
    env: {
      ...process.env,
      HOME: sb.home,
      USERPROFILE: sb.home,
      LYKOS_PI_HOST_DIR: join(sb.home, ".lykos", "pi-host"),
    },
    timeout: 60_000,
  });
}

function show(r: SpawnSyncReturns<string>): string {
  return `exit ${r.status}\nstdout:\n${r.stdout}\nstderr:\n${r.stderr}`;
}

function writeSpecialist(dir: string, name: string, body: string): void {
  mkdirSync(dir, { recursive: true });
  writeFileSync(join(dir, `${name}.yaml`), body, "utf8");
}

const projectSpecialists = (sb: Sandbox) => join(sb.project, ".lykos", "specialists");
const userSpecialists = (sb: Sandbox) => join(sb.home, ".lykos", "specialists");
const projectAgents = (sb: Sandbox) => join(sb.project, ".claude", "agents");
const userAgents = (sb: Sandbox) => join(sb.home, ".claude", "agents");

function lykosFiles(dir: string): string[] {
  if (!existsSync(dir)) return [];
  return readdirSync(dir)
    .filter((f) => f.startsWith("lykos-") && f.endsWith(".md"))
    .sort();
}

interface AgentFile {
  raw: string;
  frontmatter: Record<string, unknown>;
  body: string;
}

function readAgent(path: string): AgentFile {
  const raw = readFileSync(path, "utf8").replace(/\r\n/g, "\n");
  const m = /^---\n([\s\S]*?)\n---\n?([\s\S]*)$/.exec(raw);
  assert.ok(m, `${path} must open with a YAML frontmatter block:\n${raw}`);
  const frontmatter = parseYaml(m[1]!) as Record<string, unknown>;
  assert.ok(frontmatter && typeof frontmatter === "object", `${path}: frontmatter must be a mapping`);
  return { raw, frontmatter, body: m[2]! };
}

function toolList(v: unknown): string[] {
  if (Array.isArray(v)) return v.map((x) => String(x).trim()).filter(Boolean);
  if (typeof v === "string") return v.split(",").map((x) => x.trim()).filter(Boolean);
  return [];
}

function assertShim(dir: string, name: string, description?: string): AgentFile {
  const path = join(dir, `lykos-${name}.md`);
  assert.ok(existsSync(path), `expected ${path}`);
  const agent = readAgent(path);
  const tool = `mcp__lykos__lykos_${name}`;
  assert.equal(agent.frontmatter.name, `lykos-${name}`, `${path}: name`);
  assert.equal(agent.frontmatter.model, "haiku", `${path}: model`);
  assert.deepEqual(toolList(agent.frontmatter.tools), [tool], `${path}: tools must be exactly the one MCP tool`);
  assert.equal(typeof agent.frontmatter.description, "string", `${path}: description`);
  if (description !== undefined) {
    assert.ok(
      (agent.frontmatter.description as string).includes(description),
      `${path}: description must carry the specialist's own: ${JSON.stringify(description)}, got ${JSON.stringify(agent.frontmatter.description)}`,
    );
  }
  assert.ok(agent.raw.includes(MARKER), `${path}: must carry the generated marker "${MARKER}"`);
  assert.ok(agent.body.includes(`lykos_${name}`), `${path}: body must tell the agent to call lykos_${name}`);
  assert.match(agent.body, /unchanged|verbatim/i, `${path}: body must say to return the result unchanged`);
  return agent;
}

function readJson(path: string): Record<string, unknown> {
  return JSON.parse(readFileSync(path, "utf8")) as Record<string, unknown>;
}

function assertLykosServer(mcp: Record<string, unknown>): void {
  const servers = mcp.mcpServers as Record<string, { command?: unknown; args?: unknown }> | undefined;
  assert.ok(servers && typeof servers === "object", ".mcp.json must have mcpServers");
  const lykos = servers.lykos;
  assert.ok(lykos, ".mcp.json must have mcpServers.lykos");
  assert.equal(typeof lykos.command, "string", "mcpServers.lykos.command");
  const args = Array.isArray(lykos.args) ? lykos.args.map(String) : [];
  const line = [lykos.command as string, ...args].join(" ");
  assert.match(line, /lykos/, `mcpServers.lykos must run lykos: ${line}`);
  assert.ok(args.includes("mcp") || /(^|\s)mcp$/.test(line), `mcpServers.lykos must run \`lykos mcp\`: ${line}`);
}

describe("lykos export claude (T225)", () => {
  it("writes one marked agent file per exposed specialist and none for build or plan", () => {
    const sb = sandbox();
    try {
      const r = exportClaude(sb);
      assert.equal(r.status, 0, show(r));

      const dir = projectAgents(sb);
      const files = lykosFiles(dir);
      for (const name of BUILTIN_SUBAGENTS) assertShim(dir, name);
      assert.ok(!files.includes("lykos-build.md"), "build is primary and must not be exported");
      assert.ok(!files.includes("lykos-plan.md"), "plan is primary and must not be exported");

      // Exactly the loader's subagent set, no more.
      const expected = discoverSpecialists(sb.project, join(sb.home, ".lykos"))
        .filter((s) => s.role !== "primary")
        .map((s) => `lykos-${s.name}.md`)
        .sort();
      assert.deepEqual(files, expected);

      // The description comes from the shipped specialist file.
      const explore = discoverSpecialists(sb.project, join(sb.home, ".lykos")).find((s) => s.name === "explore");
      assertShim(dir, "explore", explore?.description);
    } finally {
      sb.cleanup();
    }
  });

  it("project beats user beats built-in; a user specialist is exposed; primary is not, all is", () => {
    const sb = sandbox();
    try {
      writeSpecialist(userSpecialists(sb), "explore", "description: User explore, overridden by the user.\nrole: subagent\nread_only: true\n");
      writeSpecialist(userSpecialists(sb), "review", "description: User review, must lose to the project.\nrole: subagent\nread_only: true\n");
      writeSpecialist(userSpecialists(sb), "helper", "description: A user-level helper specialist.\nrole: subagent\n");
      writeSpecialist(projectSpecialists(sb), "review", "description: Project review, wins over user and built-in.\nrole: subagent\nread_only: true\n");
      writeSpecialist(projectSpecialists(sb), "general", "description: Project general, now primary.\nrole: primary\n");
      writeSpecialist(projectSpecialists(sb), "both", "description: Both roles, so also a subagent.\nrole: all\n");

      const r = exportClaude(sb);
      assert.equal(r.status, 0, show(r));
      const dir = projectAgents(sb);
      assertShim(dir, "explore", "User explore, overridden by the user.");
      const review = assertShim(dir, "review", "Project review, wins over user and built-in.");
      assert.ok(!review.raw.includes("User review"), "the user description must lose to the project's");
      assertShim(dir, "helper", "A user-level helper specialist.");
      const files = lykosFiles(dir);
      assert.ok(!files.includes("lykos-general.md"), "a project override to role primary hides the built-in subagent");
      assert.ok(files.includes("lykos-both.md"), "role: all is exposed: it is usable as a subagent");
    } finally {
      sb.cleanup();
    }
  });

  it(".mcp.json gains the lykos server entry and keeps every other entry", () => {
    const sb = sandbox();
    try {
      const other = { command: "node", args: ["other-server.js"], env: { KEEP: "1" } };
      writeFileSync(
        join(sb.project, ".mcp.json"),
        JSON.stringify({ mcpServers: { other }, someTopLevelKey: { keep: true } }, null, 2),
        "utf8",
      );
      const r = exportClaude(sb);
      assert.equal(r.status, 0, show(r));
      const mcp = readJson(join(sb.project, ".mcp.json"));
      assertLykosServer(mcp);
      assert.deepEqual((mcp.mcpServers as Record<string, unknown>).other, other, "the other server entry must be kept as it was");
      assert.deepEqual(mcp.someTopLevelKey, { keep: true }, "other top-level keys must be kept");
    } finally {
      sb.cleanup();
    }
  });

  it("creates .mcp.json when the project has none", () => {
    const sb = sandbox();
    try {
      const r = exportClaude(sb);
      assert.equal(r.status, 0, show(r));
      assertLykosServer(readJson(join(sb.project, ".mcp.json")));
    } finally {
      sb.cleanup();
    }
  });

  it("refuses a hand-written lykos-<name>.md: left unchanged, named, non-zero exit, the rest still written", () => {
    const sb = sandbox();
    try {
      const dir = projectAgents(sb);
      mkdirSync(dir, { recursive: true });
      const handWritten = "---\nname: lykos-review\ndescription: My own review agent.\n---\n\nI wrote this myself.\n";
      writeFileSync(join(dir, "lykos-review.md"), handWritten, "utf8");

      const r = exportClaude(sb);
      assert.notEqual(r.status, 0, `a refusal must exit non-zero\n${show(r)}`);
      assert.equal(readFileSync(join(dir, "lykos-review.md"), "utf8"), handWritten, "a file it did not generate must never be overwritten");
      assert.match(r.stderr, /lykos-review\.md/, `the refusal must name the file\n${show(r)}`);
      assertShim(dir, "explore");
      assertShim(dir, "implementer");
    } finally {
      sb.cleanup();
    }
  });

  it("re-running regenerates its own files: a changed description shows up", () => {
    const sb = sandbox();
    try {
      writeSpecialist(projectSpecialists(sb), "helper", "description: First description of helper.\nrole: subagent\n");
      const first = exportClaude(sb);
      assert.equal(first.status, 0, show(first));
      assertShim(projectAgents(sb), "helper", "First description of helper.");

      writeSpecialist(projectSpecialists(sb), "helper", "description: Second description of helper.\nrole: subagent\n");
      const second = exportClaude(sb);
      assert.equal(second.status, 0, `re-running over its own files must succeed\n${show(second)}`);
      const agent = assertShim(projectAgents(sb), "helper", "Second description of helper.");
      assert.ok(!agent.raw.includes("First description of helper."), "the old description must be gone");
      assertShim(projectAgents(sb), "explore");
    } finally {
      sb.cleanup();
    }
  });

  it("deletes its own file for a specialist no longer exposed, never an unmarked one", () => {
    const sb = sandbox();
    try {
      writeSpecialist(projectSpecialists(sb), "scratch", "description: Temporary specialist.\nrole: subagent\n");
      const first = exportClaude(sb);
      assert.equal(first.status, 0, show(first));
      assertShim(projectAgents(sb), "scratch");

      // An unrelated hand-written agent with the lykos- prefix but no matching specialist.
      const mine = "---\nname: lykos-mine\ndescription: Hand-written.\n---\n\nMine.\n";
      writeFileSync(join(projectAgents(sb), "lykos-mine.md"), mine, "utf8");
      // A non-lykos agent the user keeps beside them.
      writeFileSync(join(projectAgents(sb), "reviewer.md"), "---\nname: reviewer\n---\n\nKeep me.\n", "utf8");

      rmSync(join(projectSpecialists(sb), "scratch.yaml"));
      const second = exportClaude(sb);
      assert.equal(second.status, 0, show(second));
      assert.ok(!existsSync(join(projectAgents(sb), "lykos-scratch.md")), "a stale generated shim must be deleted");
      assert.equal(readFileSync(join(projectAgents(sb), "lykos-mine.md"), "utf8"), mine, "an unmarked lykos- file is never deleted");
      assert.ok(existsSync(join(projectAgents(sb), "reviewer.md")), "a non-lykos agent is never touched");
      assertShim(projectAgents(sb), "explore");
    } finally {
      sb.cleanup();
    }
  });

  it("--global writes to ~/.claude/agents, leaves the project and ~/.claude.json alone, and prints the claude mcp add command", () => {
    const sb = sandbox();
    try {
      const claudeJson = join(sb.home, ".claude.json");
      const claudeJsonBody = JSON.stringify({ mcpServers: { other: { command: "x" } }, numStartups: 3 }, null, 2);
      writeFileSync(claudeJson, claudeJsonBody, "utf8");

      const r = exportClaude(sb, ["--global"]);
      assert.equal(r.status, 0, show(r));
      for (const name of BUILTIN_SUBAGENTS) assertShim(userAgents(sb), name);
      assert.ok(!lykosFiles(userAgents(sb)).includes("lykos-build.md"));
      assert.ok(!existsSync(join(sb.project, ".claude")), "--global must not write the project's .claude/");
      assert.ok(!existsSync(join(sb.project, ".mcp.json")), "--global must not write the project's .mcp.json");
      assert.equal(readFileSync(claudeJson, "utf8"), claudeJsonBody, "--global must not edit ~/.claude.json");
      assert.match(r.stdout, /claude mcp add\b.*\blykos\b.*\bmcp\b/, `--global must print the claude mcp add command\n${show(r)}`);
      assert.match(r.stdout, /--scope user|-s user/, `the printed command must be user scope\n${show(r)}`);
    } finally {
      sb.cleanup();
    }
  });
});
