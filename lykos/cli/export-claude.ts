// `lykos export claude`. Generates Claude Code agent files per exposed Lykos
// specialist, each a thin Haiku shim calling the specialist's MCP tool
// `lykos_<name>`, and configures `.mcp.json` (ADR-0056).

import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { join } from "node:path";
import {
  discoverSpecialists,
  isReservedAsyncTool,
  resolveSpecialistToolWinners,
  shippedSpecialistsDir,
  specialistToolName,
} from "../config/specialists.js";
import { stderrWrite, stdoutWrite } from "../tui/io-mode.js";

export const CLAUDE_AGENT_MARKER = "generated by lykos export claude";

export interface ExportClaudeOptions {
  global?: boolean;
  globalDir?: string;
  shippedDir?: string;
  homeDir?: string;
}

export function renderClaudeAgentFile(name: string, description: string): string {
  const quotedDesc = JSON.stringify(description);
  // The same name `lykos mcp` serves the specialist under (T222).
  const tool = specialistToolName(name);
  name = tool.slice("lykos_".length);
  return [
    "---",
    `# ${CLAUDE_AGENT_MARKER}`,
    `name: lykos-${name}`,
    `description: ${quotedDesc}`,
    "model: haiku",
    `tools: mcp__lykos__${tool}`,
    "---",
    "",
    `Call \`mcp__lykos__${tool}\` with the brief you were given, passed through as the brief, and return the tool's result unchanged, doing no work of your own.`,
    "",
  ].join("\n");
}

export function isMarkedClaudeAgent(filePath: string): boolean {
  try {
    const content = readFileSync(filePath, "utf8");
    return content.includes(CLAUDE_AGENT_MARKER);
  } catch {
    return false;
  }
}

export function runExportClaude(cwd: string, opts: ExportClaudeOptions = {}): number {
  const isGlobal = opts.global ?? false;
  const homeDir = opts.homeDir ?? homedir();
  const globalDir = opts.globalDir ?? join(homeDir, ".lykos");
  const shippedDir = opts.shippedDir ?? shippedSpecialistsDir();

  let hadError = false;

  // Ruling 2: Exposed = every specialist whose effective role is subagent or all (only primary is hidden).
  // A file T222's discovery could not read gets no shim, as `lykos mcp` serves no tool for it.
  const discovered = discoverSpecialists(cwd, globalDir, shippedDir);
  for (const s of discovered.filter((s) => s.unreadable)) {
    stderrWrite(`lykos export claude: skipped ${s.name}: its specialist file is unreadable or has an invalid role\n`);
  }

  const winningSpecialists = resolveSpecialistToolWinners(discovered);
  const eligibleSpecialists = new Map<string, (typeof discovered)[number]>();
  for (const [toolName, spec] of winningSpecialists) {
    if (isReservedAsyncTool(toolName)) {
      stderrWrite(`lykos export claude: specialist ${spec.name} clashes with async tool ${toolName}, skipping\n`);
      continue;
    }
    eligibleSpecialists.set(toolName, spec);
  }

  const exposedToolSuffixes = new Set(
    [...eligibleSpecialists.keys()].map((toolName) => toolName.slice("lykos_".length)),
  );

  const targetAgentsDir = isGlobal
    ? join(homeDir, ".claude", "agents")
    : join(cwd, ".claude", "agents");

  const writtenFiles: string[] = [];
  const deletedFiles: string[] = [];

  // Ruling 9: Delete stale shims (marked files whose specialist is no longer exposed).
  if (existsSync(targetAgentsDir)) {
    try {
      const entries = readdirSync(targetAgentsDir, { withFileTypes: true });
      for (const entry of entries) {
        if (entry.isFile() && entry.name.startsWith("lykos-") && entry.name.endsWith(".md")) {
          const specName = entry.name.slice("lykos-".length, -".md".length);
          if (!exposedToolSuffixes.has(specName)) {
            const filePath = join(targetAgentsDir, entry.name);
            if (isMarkedClaudeAgent(filePath)) {
              rmSync(filePath);
              deletedFiles.push(filePath);
            }
          }
        }
      }
    } catch (err) {
      stderrWrite(`lykos export claude: error scanning ${targetAgentsDir}: ${(err as Error).message}\n`);
      hadError = true;
    }
  }

  // Ruling 3, 4, 7, 8: Write agent file per exposed specialist.
  for (const [toolName, spec] of eligibleSpecialists) {
    const filename = `lykos-${toolName.slice("lykos_".length)}.md`;
    const filePath = join(targetAgentsDir, filename);
    const desc = spec.description || `Lykos specialist ${spec.name}`;

    if (existsSync(filePath)) {
      if (!isMarkedClaudeAgent(filePath)) {
        stderrWrite(`lykos export claude: refused to overwrite hand-written agent ${filePath}\n`);
        hadError = true;
        continue;
      }
    }

    try {
      mkdirSync(targetAgentsDir, { recursive: true });
      const content = renderClaudeAgentFile(spec.name, desc);
      writeFileSync(filePath, content, "utf8");
      writtenFiles.push(filePath);
    } catch (err) {
      stderrWrite(`lykos export claude: failed to write ${filePath}: ${(err as Error).message}\n`);
      hadError = true;
    }
  }

  // Ruling 5, 6: Project scope updates .mcp.json; --global prints claude mcp add.
  let mcpPath: string | undefined;
  let mcpWritten = false;
  if (!isGlobal) {
    mcpPath = join(cwd, ".mcp.json");
    let mcpObj: Record<string, unknown> = {};
    let mcpUnparseable = false;

    if (existsSync(mcpPath)) {
      try {
        const raw = readFileSync(mcpPath, "utf8");
        const parsed = JSON.parse(raw);
        if (typeof parsed !== "object" || parsed === null || Array.isArray(parsed)) {
          stderrWrite(`lykos export claude: unparseable JSON in ${mcpPath}\n`);
          mcpUnparseable = true;
          hadError = true;
        } else {
          mcpObj = parsed;
        }
      } catch {
        stderrWrite(`lykos export claude: unparseable JSON in ${mcpPath}\n`);
        mcpUnparseable = true;
        hadError = true;
      }
    }

    if (!mcpUnparseable) {
      try {
        const servers =
          typeof mcpObj.mcpServers === "object" && mcpObj.mcpServers !== null && !Array.isArray(mcpObj.mcpServers)
            ? (mcpObj.mcpServers as Record<string, unknown>)
            : {};
        servers.lykos = { command: "lykos", args: ["mcp"] };
        mcpObj.mcpServers = servers;
        writeFileSync(mcpPath, `${JSON.stringify(mcpObj, null, 2)}\n`, "utf8");
        mcpWritten = true;
      } catch (err) {
        stderrWrite(`lykos export claude: failed to write ${mcpPath}: ${(err as Error).message}\n`);
        hadError = true;
      }
    }
  }

  // Ruling 10: Output via stdoutWrite.
  for (const f of writtenFiles) {
    stdoutWrite(`wrote ${f}\n`);
  }
  for (const f of deletedFiles) {
    stdoutWrite(`deleted ${f}\n`);
  }
  if (!isGlobal) {
    if (mcpWritten && mcpPath !== undefined) {
      stdoutWrite(`${mcpPath}\n`);
    }
  } else {
    stdoutWrite("claude mcp add --scope user lykos -- lykos mcp\n");
  }

  return hadError ? 1 : 0;
}
